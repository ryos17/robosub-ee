"""Write paper/results_placeholder.tex: every macro of results_real.tex, typeset as a visible [XX].

The abstract inputs results_real.tex (written by scripts/make_paper_numbers.py from a scored pool
session) when it exists, else this placeholder. The placeholder is generated with the same
build_macros() as the real file, for the default pool plan (quiet at 1, 3 and 6 m; pool and bubble
noise added at 0 and 5 dB SNR; live bubbles at 3 m; systems C0, C1, C2, C10, C8), so the two files
define the same macro names. Re-run after changing the plan or make_paper_numbers.py:

    python paper/make_results_placeholder.py          # from the uw_speech_enhancement root

``build_nums`` is also used by tmp/ test scripts to make a fake results_real.tex.
"""
from __future__ import annotations

import importlib.util
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("make_paper_numbers", ROOT / "scripts" / "make_paper_numbers.py")
MPN = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(MPN)

PLACEHOLDER = r"\textbf{[XX]}"
POSITIONS = ["p1", "p3", "p6"]
DISTANCES = {"p1": 1.0, "p3": 3.0, "p6": 6.0, "p3bub": 3.0}
SYSTEMS = ["C0", "C1", "C2", "C10", "C8"]
CONDS = {"quiet": POSITIONS, "pool0dB": POSITIONS, "pool5dB": POSITIONS, "bubble0dB": POSITIONS,
         "bubble5dB": POSITIONS, "bubblelive": ["p3bub"]}


def build_nums(value=None, pilot: dict | None = None, chainref: dict | None = None,
               n_utts: int | None = None, n_spk: int | None = None) -> dict:
    """nums in the shape of make_paper_numbers.collect(). value(cond, sys, pos) -> (wer, lo, hi) or None
    (missing); deltas are taken against C0 with the CI half-width of the system."""
    nan = math.nan
    conds = {}
    for cond, poss in CONDS.items():
        wer, dwer, nu, ns = {}, {}, {}, {}
        for s in SYSTEMS:
            for p in poss:
                w = value(cond, s, p) if value else None
                wer[(s, p)] = {"wer": w[0], "lo": w[1], "hi": w[2], "n": n_utts or 0} if w else \
                    {"wer": nan, "lo": nan, "hi": nan, "n": 0}
            if value:
                allv = [wer[(s, p)]["wer"] for p in poss]
                m = sum(allv) / len(allv)
                wer[(s, "ALL")] = {"wer": m, "lo": m * 0.85, "hi": m * 1.15, "n": (n_utts or 0) * len(poss)}
        if value:
            for s in SYSTEMS[1:]:
                for p in ["ALL", *poss]:
                    d = wer[(s, p)]["wer"] - wer[("C0", p)]["wer"]
                    h = 0.25 * abs(d) + 0.004
                    dwer[(s, p)] = {"d": d, "lo": d - h, "hi": d + h, "n": n_utts or 0}
            for p in ["ALL", *poss]:
                nu[p] = (n_utts or 0) * (len(poss) if p == "ALL" else 1)
                ns[p] = n_spk or 0
        conds[cond] = {"wer": wer, "dwer": dwer, "n_utts": nu, "n_spk": ns, "positions": poss,
                       "added_noise": cond not in ("quiet", "bubblelive"), "systems": SYSTEMS}
    index = {"n_boot_ci": 10000, "n_boot_paired": 2000, "c8_sha256": "5063f02f"}
    return {"index": index, "positions": POSITIONS, "distances": DISTANCES, "conds": conds,
            "pilot": pilot, "chainref": chainref}


def write(path: Path, nums: dict, source: str, placeholder: bool) -> int:
    macros = MPN.build_macros(nums)
    if placeholder:
        macros = [(n, v.replace(MPN.MISSING, PLACEHOLDER), d) for n, v, d in macros]
        # left as plan values: PilotThreshold, NDist, DistList (default 1, 3, 6 m), NBootCI,
        # NBootPaired, CEightSha; everything measured is a visible [XX]
    MPN.write_tex(path, macros, Path(source))
    if placeholder:
        txt = path.read_text(encoding="utf-8").replace(
            "% Generated by scripts/make_paper_numbers.py from",
            "% PLACEHOLDER (no pool results yet). Generated by paper/make_results_placeholder.py with the\n"
            "% build_macros() of scripts/make_paper_numbers.py, for")
        path.write_text(txt, encoding="utf-8", newline="\n")
    return len(macros)


if __name__ == "__main__":
    out = ROOT / "paper" / "results_placeholder.tex"
    n = write(out, build_nums(), "the default pool plan (no data)", placeholder=True)
    print(f"{n} placeholder macros -> {out}")
