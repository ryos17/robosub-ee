"""Playback blocks, ABBA thruster schedule and playback budget (RESEARCH_PLAN.md 6.5, 6.6).

Block layout (6.5), all durations exact in samples at ``fs`` (default 48 kHz)::

    [0.5 s silence][LFM chirp 0.25 s][0.5 s][utt1][1.0 s]...[uttN][0.5 s][LFM chirp][2.0 s silence]

Fixed overhead for N utterances is 4.0 s + (N - 1) x 1.0 s; for N = 8 at the
test-clean mean of 7.4 s that is 11.0 s of a 70.2 s block = 15.7 % ("about
16 %" in the plan). See :func:`playback_budget` for the consequence for the
session total.

Synchronization chirp (shared with ``uwse.evaluation.align``; keep identical):

- linear FM, instantaneous frequency f0 + (f1 - f0) t / T, 0 <= t < T;
- ``x[n] = A * w[n] * sin(2 pi (f0 t + (f1 - f0) t^2 / (2 T)))``, t = n / fs,
  phase 0 at n = 0;
- T = N / fs with N = round(0.25 fs), f0 = f_lo = 500 Hz (default; set from
  the projector band), f1 = 8 kHz, w = continuous Tukey(0.1) window
  (12.5 ms raised-cosine tapers) evaluated at t = n / fs;
- peak amplitude A = -20 dBFS by default (playback level is set by the fixed
  per-session gain; the matched filter is level-invariant).
The chirp is band-limited by construction and is *not* passed through the
drive LPF, so the template in the timing JSON is exactly what is played.
The sampled waveform is produced by :func:`uwse.evaluation.align.lfm_chirp`
(single source of truth), so the alignment template is bit-identical.

Utterance processing (6.5): resample to ``fs``, RMS-normalize the whole
utterance to -26 dBFS, 5 ms raised-cosine fades, then the 8 kHz drive LPF
(zero-phase Butterworth, so utterance onsets in the timing JSON are not
shifted by filter group delay). The applied gain is logged per utterance.

ABBA (6.5): within each position, content block j is played thruster-off and
thruster-on back to back, as (A, B) for even j and (B, A) for odd j, so the
state sequence reads A B B A A B B A ... Every content block therefore occurs
in both states, adjacent in time. Drift anchor: the first played block of the
session is repeated at the end (``anchor_repeat = True``).
"""

from __future__ import annotations

import json
import math
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterable, Sequence

import numpy as np
from scipy.signal import butter, sosfiltfilt
from tqdm import tqdm

from uwse import audio
from uwse.evaluation import align as _align

FS_PLAYBACK = 48000
TARGET_RMS_DBFS = -26.0
DRIVE_LPF_HZ = 8000.0
DRIVE_LPF_ORDER = 8          # per pass; sosfiltfilt doubles the effective order
FADE_S = 0.005

CHIRP_DURATION_S = _align.DEFAULT_CHIRP_S
CHIRP_F0_HZ = _align.DEFAULT_F_LO   # f_lo, default; set from the projector usable band
CHIRP_F1_HZ = _align.DEFAULT_F_HI
CHIRP_TUKEY_ALPHA = _align.DEFAULT_TUKEY_ALPHA
CHIRP_PEAK_DBFS = _align.DEFAULT_CHIRP_PEAK_DBFS

STATES = ("off", "on")


@dataclass(frozen=True)
class BlockLayout:
    """Silences and chirp length of a playback block, in seconds (6.5)."""
    lead_silence_s: float = 0.5
    chirp_s: float = CHIRP_DURATION_S
    post_chirp_s: float = 0.5
    inter_utt_s: float = 1.0
    pre_chirp_s: float = 0.5
    tail_silence_s: float = 2.0

    def samples(self, fs: int) -> dict[str, int]:
        return {k: int(round(v * fs)) for k, v in asdict(self).items()}

    def overhead_s(self, n_utts: int) -> float:
        return (self.lead_silence_s + 2 * self.chirp_s + self.post_chirp_s
                + self.pre_chirp_s + self.tail_silence_s
                + max(n_utts - 1, 0) * self.inter_utt_s)


# ------------------------------------------------------------------ signals
def lfm_chirp(fs: int = FS_PLAYBACK, duration_s: float = CHIRP_DURATION_S,
              f0: float = CHIRP_F0_HZ, f1: float = CHIRP_F1_HZ,
              tukey_alpha: float = CHIRP_TUKEY_ALPHA,
              peak_dbfs: float = CHIRP_PEAK_DBFS) -> np.ndarray:
    """Tukey-windowed linear FM sweep f0 -> f1, generated by ``uwse.evaluation.align.lfm_chirp``."""
    n = int(round(duration_s * fs))
    if not 0 < f0 < f1 < fs / 2:  # strict, as in uwse.evaluation.align.lfm_chirp
        raise ValueError(f"need 0 < f0 < f1 < fs/2, got f0={f0}, f1={f1}, fs={fs}")
    T = n / fs
    return _align.lfm_chirp(fs, f0, f1, duration=T, fade_s=tukey_alpha * T / 2.0,
                            amplitude=10.0 ** (peak_dbfs / 20.0))


def drive_lpf(x: np.ndarray, fs: int, fc: float = DRIVE_LPF_HZ,
              order: int = DRIVE_LPF_ORDER) -> np.ndarray:
    """Zero-phase Butterworth low-pass (no group delay, so timing is preserved)."""
    if fc >= fs / 2:
        return np.asarray(x, dtype=np.float64)
    sos = butter(order, fc, btype="low", fs=fs, output="sos")
    return sosfiltfilt(sos, x)


def prepare_utterance(x: np.ndarray, fs_in: int, fs: int = FS_PLAYBACK,
                      target_dbfs: float = TARGET_RMS_DBFS, lpf_hz: float = DRIVE_LPF_HZ,
                      fade_s: float = FADE_S) -> tuple[np.ndarray, dict[str, float]]:
    """Resample, RMS-normalize to ``target_dbfs``, fade, drive LPF. Returns (y, info)."""
    x = np.asarray(x, dtype=np.float64)
    if x.ndim != 1:
        raise ValueError("mono utterances only")
    y = audio.resample(x, fs_in, fs)
    r = float(audio.rms(y))
    if r <= 0:
        raise ValueError("silent utterance")
    gain_db = target_dbfs - 20.0 * math.log10(r)
    y = audio.fade(y * 10.0 ** (gain_db / 20.0), fs, fade_s, fade_s)
    y = drive_lpf(y, fs, lpf_hz)
    return y, {
        "gain_dB": gain_db,
        "rms_dBFS": float(audio.db(audio.rms(y))),
        "peak_dBFS": float(audio.db(np.max(np.abs(y)))),
    }


# ------------------------------------------------------------------ timing
def block_timing(utt_lengths: Sequence[int], fs: int = FS_PLAYBACK,
                 layout: BlockLayout = BlockLayout()) -> dict[str, Any]:
    """Sample offsets of both chirps and every utterance (end indices exclusive)."""
    s = layout.samples(fs)
    pos = s["lead_silence_s"]
    chirps = [{"start": pos, "end": pos + s["chirp_s"]}]
    pos += s["chirp_s"] + s["post_chirp_s"]
    utts = []
    for i, n in enumerate(utt_lengths):
        utts.append({"start": pos, "end": pos + int(n)})
        pos += int(n)
        if i < len(utt_lengths) - 1:
            pos += s["inter_utt_s"]
    pos += s["pre_chirp_s"]
    chirps.append({"start": pos, "end": pos + s["chirp_s"]})
    pos += s["chirp_s"] + s["tail_silence_s"]
    return {"fs": fs, "n_samples": pos, "chirps": chirps, "utterances": utts}


def overhead_fraction(n_utts: int, mean_dur_s: float,
                      layout: BlockLayout = BlockLayout()) -> float:
    """Non-speech share of a block's playback time."""
    oh = layout.overhead_s(n_utts)
    return oh / (oh + n_utts * mean_dur_s)


# ------------------------------------------------------------------ packing
def pack_blocks(items: Sequence[Any], durations_s: Sequence[float] | None = None,
                target_speech_s: float = 60.0, max_utts: int | None = None,
                seed: int | None = 0) -> list[list[Any]]:
    """Group items into blocks of about ``target_speech_s`` of speech.

    Items are shuffled with ``seed`` (None keeps the order) so speakers mix
    across blocks; an item joins the current block while that brings the
    block's speech time closer to the target. ``durations_s`` defaults to
    ``item.duration_s``.
    """
    if durations_s is None:
        durations_s = [float(it.duration_s) for it in items]
    if len(durations_s) != len(items):
        raise ValueError("durations_s and items differ in length")
    bad = [i for i, d in enumerate(durations_s) if not (math.isfinite(float(d)) and float(d) > 0)]
    if bad:
        # NaN (manifest built with_duration=False) would never close a block.
        raise ValueError(f"{len(bad)} items have non-finite or non-positive durations, e.g. index {bad[0]}")
    order = list(range(len(items)))
    if seed is not None:
        order = list(np.random.default_rng(seed).permutation(len(items)))
    blocks: list[list[Any]] = []
    cur: list[Any] = []
    s = 0.0
    for i in order:
        d = float(durations_s[i])
        full = max_utts is not None and len(cur) >= max_utts
        if cur and (full or abs(s + d - target_speech_s) > abs(s - target_speech_s)):
            blocks.append(cur)
            cur, s = [], 0.0
        cur.append(items[i])
        s += d
    if cur:
        blocks.append(cur)
    return blocks


# ------------------------------------------------------------------ schedule
@dataclass
class ScheduleEntry:
    session_order_idx: int
    block_id: int              # playback block index within the session (utt_id "bNN")
    content_block: str         # rendered WAV/JSON stem
    position_id: str
    thruster_state: str
    block_order: str = "ABBA"
    anchor_repeat: bool = False


def abba_states(n: int, first: str = "off") -> list[str]:
    """First ``n`` states of A B B A A B B A ... with A = ``first``."""
    if first not in STATES:
        raise ValueError(f"first must be one of {STATES}")
    a, b = first, STATES[1 - STATES.index(first)]
    return [(a, b, b, a)[i % 4] for i in range(n)]


def session_schedule(positions: Sequence[str], content_blocks: Sequence[str],
                     first_state: str = "off", thruster: bool = True,
                     anchor: bool = True) -> list[ScheduleEntry]:
    """Playback order for one session.

    With ``thruster`` each content block is played in both states per
    position in ABBA order; without it every block is played once, off.
    With ``anchor`` the first entry is repeated at the end as drift anchor
    (it is the same audio at the same position and state, so the projector
    and array must be returned to that position for the final block).
    """
    out: list[ScheduleEntry] = []
    for pos in positions:
        if thruster:
            states = abba_states(2 * len(content_blocks), first_state)
            pairs = [(cb, states[2 * j + k]) for j, cb in enumerate(content_blocks) for k in (0, 1)]
        else:
            pairs = [(cb, "off") for cb in content_blocks]
        for cb, st in pairs:
            i = len(out)
            out.append(ScheduleEntry(i, i, cb, pos, st))
    if anchor and out:
        i = len(out)
        f = out[0]
        out.append(ScheduleEntry(i, i, f.content_block, f.position_id, f.thruster_state,
                                 anchor_repeat=True))
    return out


def write_schedule(path: str | Path, schedule: Iterable[ScheduleEntry]) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump([asdict(e) for e in schedule], f, indent=1)


def read_schedule(path: str | Path) -> list[ScheduleEntry]:
    with open(path, "r", encoding="utf-8") as f:
        return [ScheduleEntry(**d) for d in json.load(f)]


# ------------------------------------------------------------------ rendering
def chirp_params(fs: int = FS_PLAYBACK, f0: float = CHIRP_F0_HZ, f1: float = CHIRP_F1_HZ,
                 peak_dbfs: float = CHIRP_PEAK_DBFS,
                 duration_s: float = CHIRP_DURATION_S) -> dict[str, Any]:
    return {"type": "lfm", "duration_s": duration_s, "f0_hz": f0, "f1_hz": f1,
            "window": "tukey", "tukey_alpha": CHIRP_TUKEY_ALPHA, "peak_dBFS": peak_dbfs,
            "phase": "sin, 0 at first sample", "fs": fs}


def render_block(items: Sequence[tuple[str, np.ndarray, int]], fs: int = FS_PLAYBACK,
                 layout: BlockLayout = BlockLayout(), f_lo: float = CHIRP_F0_HZ,
                 chirp_peak_dbfs: float = CHIRP_PEAK_DBFS,
                 target_dbfs: float = TARGET_RMS_DBFS,
                 lpf_hz: float = DRIVE_LPF_HZ) -> tuple[np.ndarray, dict[str, Any]]:
    """Assemble one block from ``(item_id, audio, fs_in)`` tuples.

    Returns the mono playback signal and its timing dict (sample offsets at
    ``fs``, per-utterance gains, chirp parameters). Raises if the block clips.
    """
    if not items:
        raise ValueError("empty block")
    prepared = [prepare_utterance(x, f_in, fs, target_dbfs, lpf_hz) for _, x, f_in in items]
    timing = block_timing([len(y) for y, _ in prepared], fs, layout)
    sig = np.zeros(timing["n_samples"], dtype=np.float64)
    ch = lfm_chirp(fs, layout.chirp_s, f_lo, CHIRP_F1_HZ, CHIRP_TUKEY_ALPHA, chirp_peak_dbfs)
    for c in timing["chirps"]:
        sig[c["start"]:c["end"]] = ch
    for (item_id, _, f_in), (y, info), t in zip(items, prepared, timing["utterances"]):
        sig[t["start"]:t["end"]] = y
        t.update({"item_id": item_id, "src_fs": f_in, **info})
    peak = float(np.max(np.abs(sig)))
    if peak >= 1.0:
        raise ValueError(f"block clips (peak {peak:.3f}); lower target_dbfs or drop the item")
    timing["peak_dBFS"] = float(audio.db(peak))
    timing["target_rms_dBFS"] = target_dbfs
    timing["drive_lpf_hz"] = lpf_hz
    timing["layout"] = asdict(layout)
    timing["chirp"] = chirp_params(fs, f_lo, CHIRP_F1_HZ, chirp_peak_dbfs, layout.chirp_s)
    return sig, timing


def render_blocks(blocks: Sequence[Sequence[Any]], out_dir: str | Path, prefix: str = "block",
                  fs: int = FS_PLAYBACK, layout: BlockLayout = BlockLayout(),
                  f_lo: float = CHIRP_F0_HZ, bench_split: str | None = None,
                  **kw: Any) -> list[str]:
    """Render blocks of Utterance-like items (``utt_id``, ``path``) to WAV + timing JSON.

    Files are ``<out_dir>/<prefix>_NNN.wav`` (48 kHz, 24-bit) and ``.json``.
    Returns the stems, which are the ``content_block`` names of the schedule.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    stems = []
    for k, blk in enumerate(tqdm(blocks, desc=f"render {prefix}")):
        items = []
        for u in blk:
            x, f_in = audio.load(u.path)
            items.append((u.utt_id, x, f_in))
        sig, timing = render_block(items, fs, layout, f_lo, **kw)
        for t, u in zip(timing["utterances"], blk):
            t["src_path"] = str(u.path)
            if hasattr(u, "transcript"):
                t["transcript"] = u.transcript
        stem = f"{prefix}_{k:03d}"
        timing["content_block"] = stem
        timing["bench_split"] = bench_split
        audio.save(str(out_dir / f"{stem}.wav"), sig, fs, subtype="PCM_24")
        with open(out_dir / f"{stem}.json", "w", encoding="utf-8", newline="\n") as f:
            json.dump(timing, f, indent=1)
        stems.append(stem)
    return stems


# ------------------------------------------------------------------ budget
@dataclass
class Budget:
    test_speech_h: float
    total_plan_h: float           # plan formula: speech x 1.16
    total_layout_h: float         # from the actual block layout
    overhead_fraction: float      # non-speech share of block time
    overhead_ratio: float         # non-speech time / speech time
    n_blocks_per_condition: int
    notes: list[str] = field(default_factory=list)


def playback_budget(n_positions: int = 3, n_states: int = 2, n_test: int = 200, n_dev: int = 40,
                    mean_dur_s: float = 7.4, utts_per_block: int = 8,
                    layout: BlockLayout = BlockLayout(), plan_multiplier: float = 1.16,
                    anchor_blocks: int = 0) -> Budget:
    """Session playback time (6.6 / Appendix A) under the plan formula and the real layout.

    Each condition (position x thruster state) plays the same test + dev set.
    Dev and test are packed in separate blocks of ``utts_per_block``.
    """
    n_cond = n_positions * n_states
    test_h = n_cond * n_test * mean_dur_s / 3600.0
    plan_h = n_cond * (n_test + n_dev) * mean_dur_s * plan_multiplier / 3600.0
    full_blocks = []
    for n in (n_test, n_dev):
        q, r = divmod(n, utts_per_block)
        full_blocks += [utts_per_block] * q + ([r] if r else [])
    per_cond_s = sum(layout.overhead_s(b) + b * mean_dur_s for b in full_blocks)
    anchor_s = anchor_blocks * (layout.overhead_s(utts_per_block) + utts_per_block * mean_dur_s)
    layout_h = (n_cond * per_cond_s + anchor_s) / 3600.0
    frac = overhead_fraction(utts_per_block, mean_dur_s, layout)
    ratio = frac / (1.0 - frac)
    notes = []
    if abs(ratio - (plan_multiplier - 1.0)) > 0.005:
        notes.append(
            f"overhead is {100 * frac:.1f}% of block time but {100 * ratio:.1f}% of speech time; "
            f"the plan multiplies speech by {plan_multiplier:.2f}, the layout implies "
            f"{1 + ratio:.3f} -> {layout_h:.2f} h instead of {plan_h:.2f} h")
    return Budget(test_h, plan_h, layout_h, frac, ratio, len(full_blocks), notes)
